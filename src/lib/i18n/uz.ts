function translateValue(value: string): string {
  const trimmed = value.trim();
  if (!trimmed) return value;
  let translated = exact[trimmed];
  // Preserve keyboard shortcuts and status suffixes, e.g. "Undo (Ctrl+Z)".
  if (!translated) {
    const suffix = trimmed.match(/^(.+?) \(([^)]+)\)$/);
    if (suffix && exact[suffix[1]]) translated = `${exact[suffix[1]]} (${suffix[2]})`;
  }
  if (!translated) {
    for (const [re, fn] of regex) {
      const match = trimmed.match(re);
      if (match) {
        translated = fn(match);
        break;
      }
    }
  }
  if (!translated || translated === trimmed) return value;
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  return `${leading}${translated}${trailing}`;
}

function translateElement(el: Element) {
  const attrs = ['title', 'aria-label', 'placeholder', 'alt'];
  for (const attr of attrs) {
    const v = el.getAttribute(attr);
    if (v) {
      const t = translateValue(v);
      if (t !== v) el.setAttribute(attr, t);
    }
  }
  for (const child of Array.from(el.childNodes)) {
    if (child.nodeType === Node.TEXT_NODE && child.textContent) {
      const t = translateValue(child.textContent);
      if (t !== child.textContent) child.textContent = t;
    }
  }
}

function translateTree(root: ParentNode) {
  if (root instanceof Element) translateElement(root);
  root.querySelectorAll?.('*').forEach(translateElement);
}

function wrapDialogs() {
  const rawAlert = window.alert.bind(window);
  const rawConfirm = window.confirm.bind(window);
  const rawPrompt = window.prompt.bind(window);
  window.alert = (message?: any) => rawAlert(typeof message === 'string' ? translateValue(message) : message);
  window.confirm = (message?: string) => rawConfirm(message ? translateValue(message) : message ?? '');
  window.prompt = (message?: string, defaultValue?: string) => rawPrompt(message ? translateValue(message) : message ?? '', defaultValue);
}

export function installUzbekUi() {
  if (typeof window === 'undefined' || typeof document === 'undefined') return () => {};
  document.documentElement.lang = 'uz';
  wrapDialogs();
  translateTree(document.body);

  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') {
        const node = mutation.target as CharacterData;
        if (node.data) {
          const t = translateValue(node.data);
          if (t !== node.data) node.data = t;
        }
        continue;
      }
      if (mutation.type === 'attributes' && mutation.target instanceof Element) {
        translateElement(mutation.target);
        continue;
      }
      for (const node of Array.from(mutation.addedNodes)) {
        if (node.nodeType === Node.TEXT_NODE && node.textContent) {
          const t = translateValue(node.textContent);
          if (t !== node.textContent) node.textContent = t;
        } else if (node instanceof Element) {
          translateTree(node);
        }
      }
    }
  });

  observer.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ['title', 'aria-label', 'placeholder', 'alt']
  });

  return () => observer.disconnect();
}
